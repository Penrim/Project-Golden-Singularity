"""GS1 -> TLA transfer without a cable + chapter transition: C runtime build and title-code patches.

All addresses come from version profiles (tools/profiles.py), so the same code works for every language version.

TLA title map code (runs at 0x02008000): the cable-receive function is replaced by a read of the GS1 clear save
from flash bank 1 (runtime `tla_receive_gs1`), then TLA's own "process received data" path runs. Four small hooks
live in the now unused body of the receive function:
  hook1 before "Transfer data from Golden Sun?" -> take the Link path directly if a GS1 clear save exists
  hook2 at the title-screen call                  -> "New Game" when the chapter-2 mailbox is set
  hook3 at the per-character naming loop         -> skipped after an automatic transfer (names come from GS1)
  hook4 at the received-party overview           -> skipped after an automatic transfer
GS1 title map code: the "after the credits" branch jumps to runtime `gs1_chapter_end`.
"""
import hashlib, json, os, shutil, struct, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsfs import decompress
from compress import compress_c1
import profiles
import asmcache

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GCC = os.path.join(HERE, "armgcc", "bin")
MAPCODE_BASE = 0x02008000


def build_runtime(gp, tp):
    """Compile cart/runtime.c for one GS1/TLA version pair; returns (binary, {symbol: address})."""
    out = os.path.join(ROOT, "build", "cart", f"{gp['code']}_{tp['code']}")
    os.makedirs(out, exist_ok=True)
    header = "\n".join([
        "/* generated by tools/transfer_patch.py from tools/profiles.py - do not edit */",
        f"#define PROFILE_GS1_CODE \"{gp['code']}\"",
        f"#define PROFILE_TLA_CODE \"{tp['code']}\"",
        f"#define PROFILE_GS1_CLEAR_MARKER {gp['clear_marker']:#x}",
        f"#define PROFILE_GS1_SLOT_VAR {gp['slot_var']:#x}",
        f"#define PROFILE_GS1_FN_FLASH_SCAN {gp['fn_flash_scan']:#x}",
        f"#define PROFILE_GS1_FN_SAVE_INIT {gp['fn_save_init']:#x}",
        f"#define PROFILE_GS1_FN_PREPARE {gp['fn_prepare']:#x}",
        f"#define PROFILE_GS1_FN_ACTORS {gp['fn_actors']:#x}",
        f"#define PROFILE_GS1_FN_WRITE_SLOT {gp['fn_write_slot']:#x}",
        f"#define PROFILE_GS1_IWRAM_SRC {gp['iwram_src']:#x}",
        f"#define PROFILE_GS1_IWRAM_BYTES {gp['iwram_bytes']:#x}",
        f"#define PROFILE_GS1_M4A_INIT {gp['m4a_init']:#x}",
        f"#define PROFILE_GS1_M4A_MAIN {gp['m4a_main']:#x}",
        f"#define PROFILE_GS1_M4A_VSYNC {gp['m4a_vsync']:#x}",
        f"#define PROFILE_GS1_M4A_SONG_START {gp['m4a_song_start']:#x}",
        f"#define PROFILE_GS1_INTRO_SONG {gp['intro_song']}",
        f"#define PROFILE_GS1_INTRO_SONG_LEAD {profiles.INTRO_SONG_LEAD}",
        f"#define PROFILE_TLA_ENTRY {tp['entry']:#x}",
        f"#define PROFILE_TLA_RECV_BUFFER {tp['recv_buffer']:#x}",
        ""])
    open(os.path.join(out, "profile.h"), "w").write(header)
    pair = f"{gp['code']}_{tp['code']}"
    src_hash = hashlib.sha1(open(os.path.join(ROOT, "cart", "runtime.c"), "rb").read() +
                            open(os.path.join(ROOT, "cart", "link.ld"), "rb").read()).hexdigest()
    pre = os.path.join(ROOT, "cart", "prebuilt", pair)
    gcc = _find_gcc()
    if gcc is None or os.environ.get("GSMERGE_PREBUILT") == "1":
        # players: use the precompiled runtime (same source, same version pair) - no ARM toolchain needed
        if not os.path.exists(os.path.join(pre, "meta.json")):
            raise SystemExit(f"no precompiled runtime for {pair} in cart/prebuilt and no ARM GCC found "
                             "(see BUILDING.md, 'Developers')")
        meta = json.load(open(os.path.join(pre, "meta.json")))
        if meta["header"] != header or meta["source_sha1"] != src_hash:
            raise SystemExit(f"cart/prebuilt/{pair} does not match cart/runtime.c or the ROM profile; "
                             "install the ARM GCC toolchain to rebuild it (BUILDING.md, 'Developers')")
        return open(os.path.join(pre, "runtime.bin"), "rb").read(), meta["symbols"]
    data, syms = _compile(gcc, out)
    os.makedirs(pre, exist_ok=True)                         # developers: keep the precompiled copy up to date
    open(os.path.join(pre, "runtime.bin"), "wb").write(data)
    json.dump({"header": header, "source_sha1": src_hash, "symbols": syms}, open(os.path.join(pre, "meta.json"), "w"),
              indent=1, sort_keys=True)
    return data, syms


def _find_gcc():
    """ARM GCC bin folder: tools/armgcc/bin (as set up in BUILDING.md) or arm-none-eabi-gcc on PATH."""
    exe = ".exe" if os.name == "nt" else ""
    if os.path.exists(os.path.join(GCC, "arm-none-eabi-gcc" + exe)):
        return GCC
    found = shutil.which("arm-none-eabi-gcc")
    return os.path.dirname(found) if found else None


def _compile(gcc_dir, out):
    exe = ".exe" if os.name == "nt" else ""
    GCC = gcc_dir
    cc = os.path.join(GCC, "arm-none-eabi-gcc" + exe)
    flags = ["-mcpu=arm7tdmi", "-mthumb", "-Os", "-ffreestanding", "-nostdlib", "-fno-builtin", "-fno-pic",
             "-ffixed-r4",  # Camelot code treats r4 as scratch: never keep values in r4 across game calls
             "-Wall", "-Wextra", "-I", out]
    obj, elf, binf = (os.path.join(out, n) for n in ("runtime.o", "runtime.elf", "runtime.bin"))
    subprocess.run([cc, *flags, "-c", os.path.join(ROOT, "cart", "runtime.c"), "-o", obj], check=True)
    subprocess.run([cc, "-mcpu=arm7tdmi", "-mthumb", "-nostdlib", "-T", os.path.join(ROOT, "cart", "link.ld"),
                    obj, "-o", elf, "-lgcc"], check=True)
    subprocess.run([os.path.join(GCC, "arm-none-eabi-objcopy" + exe), "-O", "binary", elf, binf], check=True)
    syms = {}
    nm = subprocess.run([os.path.join(GCC, "arm-none-eabi-nm" + exe), elf], check=True, capture_output=True, text=True)
    for line in nm.stdout.splitlines():
        addr, kind, name = line.split()
        syms[name] = int(addr, 16)
    return open(binf, "rb").read(), syms


def to_stored_bl(blob, hi_pos, blob_pos):
    """Re-encode the normal Thumb BL at blob[hi_pos] (located at map-code offset blob_pos) into the map-code
    storage form used by TLA/GS1 (stored field = target offset in the map code - 2)."""
    hi, lo = struct.unpack_from("<HH", blob, hi_pos)
    off = (((hi & 0x7FF) << 12) | ((lo & 0x7FF) << 1))
    if off & 0x400000:
        off -= 0x800000
    target = blob_pos + 4 + off
    v = target - 2
    struct.pack_into("<HH", blob, hi_pos, 0xF000 | ((v >> 12) & 0x7FF), 0xF800 | ((v >> 1) & 0x7FF))


def _asm(src, base):
    code = bytearray(asmcache.assemble("thumb", src, base))
    for k in range(0, len(code) - 1, 2):   # ARM7TDMI: only 16-bit Thumb (BL pairs are allowed)
        h = code[k] | (code[k + 1] << 8)
        assert not (0xE800 <= h < 0xF000), f"Thumb-2 instruction at {base + k:#x}"
    return code


def _place(code, at, blob, bl_at=None):
    o = at - MAPCODE_BASE
    if bl_at is not None:
        to_stored_bl(blob, bl_at, o + bl_at)
    code[o:o + len(blob)] = blob


def _call(code, site, target):
    """Replace the 4 bytes at `site` by a (stored-form) BL to `target`."""
    _place(code, site, _asm(f"bl {target:#x}", site), bl_at=0)


def patch_tla_title(tla_data, tp, syms):
    start = struct.unpack_from("<I", tla_data, tp["mft_off"] + 4 * tp["title_mapcode"])[0] - 0x08000000
    code = bytearray(decompress(tla_data, start))
    recv_at, success = tp["recv_patch_at"], tp["recv_success"]
    hook1 = recv_at + 0x18
    hook2 = hook1 + 0x2C
    hook3 = hook2 + 0x24
    hook4 = hook3 + 0x2C
    assert recv_at % 4 == 0 and hook4 + 0x30 <= success, "hooks must fit before the success path"
    assert tp["ask_msg"] < 0x100

    _place(code, recv_at, _asm(f"""
        bl veneer
        cmp r0, #0
        beq fail
        b {success:#x}
    fail:
        movs r0, #1
        rsbs r0, r0, #0
        b {tp["recv_epilogue"]:#x}
    veneer:
        ldr r3, [pc, #0]
        bx r3
        .word {syms["tla_receive_gs1"] | 1:#x}
    """, recv_at), bl_at=0)

    h = _asm(f"""
        push {{lr}}
        bl call_rt
        pop {{r3}}
        cmp r0, #0
        beq no
        movs r5, #1
        movs r2, #1
        rsbs r2, r2, #0
        mov r8, r2
        ldr r3, [pc, #12]
        bx r3
    no:
        movs r0, #{tp["ask_msg"]:#x}
        movs r1, #13
        bx r3
    call_rt:
        ldr r3, [pc, #8]
        bx r3
        nop
        .word {tp["link_path"] | 1:#x}
        .word {syms["gs1_clear_available"] | 1:#x}
    """, hook1)
    assert len(h) == 0x2C
    _place(code, hook1, h, bl_at=2)

    h = _asm(f"""
        push {{lr}}
        bl call_rt
        cmp r0, #0
        beq normal
        movs r0, #0
        pop {{r3}}
        bx r3
    normal:
        pop {{r3}}
        mov lr, r3
        ldr r3, [pc, #4]
        bx r3
    call_rt:
        ldr r3, [pc, #4]
        bx r3
        .word {tp["title_fn"] | 1:#x}
        .word {syms["tla_title_menu_override"] | 1:#x}
    """, hook2)
    assert len(h) == 0x24
    _place(code, hook2, h, bl_at=2)

    h = _asm(f"""
        push {{lr}}
        bl call_rt
        pop {{r3}}
        cmp r0, #0
        bne skip
        movs r6, #0
        movs r7, #1
        ldr r3, [pc, #12]
        bx r3
    skip:
        ldr r3, [pc, #12]
        bx r3
    call_rt:
        ldr r3, [pc, #12]
        bx r3
        nop
        nop
        .word {tp["name_loop_body"] | 1:#x}
        .word {tp["name_loop_done"] | 1:#x}
        .word {syms["gs1_clear_available"] | 1:#x}
    """, hook3)
    assert len(h) == 0x2C
    _place(code, hook3, h, bl_at=2)

    h = _asm(f"""
        push {{r0, r1, r2, r3}}
        push {{lr}}
        bl call_rt
        pop {{r3}}
        mov ip, r3
        cmp r0, #0
        pop {{r0, r1, r2, r3}}
        bne skip
        mov lr, ip
        push {{r3}}
        ldr r3, [pc, #16]
        mov ip, r3
        pop {{r3}}
        bx ip
    skip:
        bx ip
    call_rt:
        ldr r3, [pc, #8]
        bx r3
        nop
        nop
        .word {tp["review_fn"] | 1:#x}
        .word {syms["gs1_clear_available"] | 1:#x}
    """, hook4)
    assert len(h) == 0x30
    _place(code, hook4, h, bl_at=4)

    nl = tp["name_loop"] - MAPCODE_BASE
    assert code[nl:nl + 4] == bytes.fromhex("00260127"), code[nl:nl + 4].hex()   # movs r6,#0; movs r7,#1
    _call(code, tp["title_call"], hook2)
    _call(code, tp["name_loop"], hook3)
    _call(code, tp["review_call"], hook4)
    _call(code, tp["ask_transfer"], hook1)

    comp = b"\x01" + compress_c1(bytes(code))
    assert decompress(comp + bytes(8), 0) == bytes(code)
    return comp


def patch_gs1_title(code, gp, syms):
    """GS1 title map code (decompressed, already relocated): the "cleared" branch calls gs1_chapter_end."""
    code = bytearray(code)
    at = gp["cleared_branch"]
    jump = _asm(f"""
        ldr r3, [pc, #4]
        bx r3
        nop
        .word {syms["gs1_chapter_end"] | 1:#x}
    """, at)
    assert len(jump) == 10 and (at + 6) % 4 == 0
    _place(code, at, jump)
    return bytes(code)
